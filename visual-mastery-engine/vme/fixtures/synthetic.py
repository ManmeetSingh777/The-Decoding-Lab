def make_clip(path: str | Path, *, frames: int = 24, fps: int = 60, size: str = "160x90", vfr: bool = False, audio: bool = False) -> Path:
    ff = require_tool("ffmpeg")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    dur = frames / fps + 0.5
    vf = f"trim=end_frame={frames}"
    cmd = [ff, "-v", "error", "-y", "-f", "lavfi", "-i", f"testsrc2=size={size}:rate={fps}:duration={dur}", "-vf", vf]
    if vfr:
        # irregular presentation timestamps: first half 1/60 s steps, second half 3/60 s steps
        half = frames // 2
        cmd = [ff, "-v", "error", "-y", "-f", "lavfi", "-i", f"testsrc2=size={size}:rate={fps}:duration={dur}",
               "-vf", f"trim=end_frame={frames},setpts='if(lt(N,{half}),N,{half}+(N-{half})*3)/({fps}*TB)'",
               "-fps_mode", "passthrough", "-enc_time_base", f"1/{fps}"]
    if audio:   # SYNTHETIC beeps (generated locally) so the source-audio study path executes offline; inputs precede filters
        vi = cmd.index("-vf")
        cmd = cmd[:vi] + ["-f", "lavfi", "-i", f"aevalsrc=0.5*sin(2*PI*440*t)*lt(mod(t\\,0.2)\\,0.04):s=16000:d={dur}"] + cmd[vi:] + \
            ["-map", "0:v:0", "-map", "1:a:0", "-c:a", "aac", "-shortest"]
    cmd += ["-pix_fmt", "yuv420p", "-c:v", "libx264", "-g", "12", str(path)]
    out = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if out.returncode != 0:
        raise Blocked("FIXTURE_CLIP_FAILED", out.stderr[:300])
    return path


def make_sixth_clip(path: str | Path, *, segments: list[tuple[str, int]], fps: int = 60, size: str = "160x90") -> Path:
    """Colour-segment clip: e.g. [("gray",10),("red",31),("blue",20)] — 'red'≈volcano, 'blue'≈logo in the FIXTURE classifier."""
    ff = require_tool("ffmpeg")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    inputs, filt = [], []
    for i, (color, n) in enumerate(segments):
        inputs += ["-f", "lavfi", "-i", f"color=c={color}:size={size}:rate={fps}:duration={n / fps + 0.2}"]
        filt.append(f"[{i}:v]trim=end_frame={n},setpts=PTS-STARTPTS[v{i}]")
    filt.append("".join(f"[v{i}]" for i in range(len(segments))) + f"concat=n={len(segments)}:v=1:a=0[out]")
    cmd = [ff, "-v", "error", "-y", *inputs, "-filter_complex", ";".join(filt), "-map", "[out]", "-pix_fmt", "yuv420p",
           "-c:v", "libx264", "-g", "12", str(path)]
    out = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if out.returncode != 0:
        raise Blocked("FIXTURE_CLIP_FAILED", out.stderr[:300])
    return path


def colour_classifier_factory(loader):
    """FIXTURE classifier: decodes the real frame bytes and labels red-dominant as 'volcano', blue as 'earth_logo'."""
    from PIL import ImageStat

    def classify(rec: dict) -> dict:
        fr = loader(rec)
        r, g, b = ImageStat.Stat(Image.open(io.BytesIO(fr["png"])).convert("RGB")).mean
        tot = r + g + b + 1e-6
        return {"volcano": r / tot if r > 150 and g < 90 else 0.0, "earth_logo": b / tot if b > 150 and r < 90 else 0.0}
    return classify


def _ref_png(seed: str, colour: tuple) -> bytes:
    im = Image.new("RGB", (64, 64), colour)
    d = ImageDraw.Draw(im)
    d.ellipse([12, 12, 52, 52], outline=(255, 255, 255), width=3)
    d.text((4, 2), "SYN", fill=(255, 255, 255))
    d.text((4, 50), seed[:6], fill=(255, 255, 255))
    b = io.BytesIO()
    im.save(b, format="PNG")
    return b.getvalue()


